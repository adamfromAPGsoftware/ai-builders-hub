"""Build course/<module>/README.md, course/README.md and hub-map.json from course/modules.json.

Run from the repo root after editing course/modules.json:

    python3 tools/build_course.py

Everything this writes is generated. Edit modules.json, never the outputs.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "course" / "modules.json"
COMMUNITY = "https://www.skool.com/ai-builders-hub"
MARKETPLACE = json.loads((ROOT / ".claude-plugin" / "marketplace.json").read_text())
PLUGIN = json.loads((ROOT / "plugins" / "trade-intake" / ".claude-plugin" / "plugin.json").read_text())

# The steps every member takes before any module (Skool course ids, read 22 Oct 2026).
STAGES = [
    {"stage": 1, "name": "Start here", "skool_course_id": "53665fe139b748c882788790adf360bf",
     "what": "Set up Claude, run /hub-welcome, post your welcome card on the Introductions pin."},
    {"stage": 2, "name": "Connect your tools", "skool_course_id": "eacf2bdfd0294a17905dcd490fb2acf7",
     "what": "Look up each tool from your welcome card in Claude's connectors; add what's there, note what isn't."},
]

GENERATED = "<!-- Generated by tools/build_course.py from course/modules.json. Edit that file, not this one. -->"
FLAG = {"copy": "copy-paste", "slow": "slow"}


def folder(m):
    return f"{m['n']:02d}-{m['key']}"


def lesson_link(m, lesson):
    lid, cid = lesson.get("skool_lesson_id"), m["course"].get("skool_course_id")
    if lid and cid:
        return f"[{lesson['title']}]({COMMUNITY}/classroom/{cid}?md={lid})"
    return lesson["title"]


def module_readme(m):
    c = m["course"]
    L = [GENERATED, "", f"# Module {m['n']}: {m['name']}", "", f"*{m['promise']}*", "",
         f"**Who does it in a small business:** {m['who']}.", "",
         "## The typical process", "",
         "Every business does it a bit differently. This is the common shape we see.", "",
         "| # | Step | What happens | Tools | Where time goes |", "|:-:|---|---|---|---|"]
    for i, s in enumerate(m["steps"], 1):
        L.append(f"| {i} | {s['step']} | {s['what']} | {', '.join(s['tools'])} | {FLAG.get(s['flag'], '')} |")
    L += ["", "## Where the time goes", "",
          "From businesses APG has audited, anonymised. Hours are staff estimates, not measurements.", ""]
    L += [f"- {p}" for p in m["time_goes"]]
    intake = f"`/{m['intake']['skill']}`" if m["intake"]["skill"] else "\"How we do it\" (planned)"
    L += ["", "## Step 1: map how you do it", "", f"{intake}: {m['intake']['what']}", "",
          "It hands back your own version of the map above, with your tools and your hours, "
          "then suggests which skill to build first.", "",
          "## The skills", ""]
    L += [f"- **{s['name']}** ({s['mode']}): {s['what']}" for s in m["skills"]]
    L += ["", f"## The course in the Hub: {c['title']} ({c['status']})", ""]
    for p in c["parts"]:
        L.append(f"**{p['part']}**")
        L.append("")
        L += [f"{i}. {lesson_link(m, l)}" for i, l in enumerate(p["lessons"], 1)]
        L.append("")
    if m.get("map_thread"):
        L += [f"**Post your map:** [{m['name']} map thread]({m['map_thread']}), pinned to the module.", ""]
    L += [f"**Plugin:** {m['plugin_status']}.", ""]
    return "\n".join(L)


def main():
    data = json.loads(SRC.read_text())
    mods = [m for m in data["modules"] if not m.get("parked")]
    parked = [m for m in data["modules"] if m.get("parked")]
    index = [GENERATED, "", "# AI Builders Hub modules", "",
             "Each module is a department of a trade, construction or manufacturing business. "
             "Every member starts with Stage 1 and Stage 2, then any module on the paid plan.", "",
             "| # | Module | Course | Map it with |", "|:-:|---|---|---|"]
    for m in mods:
        d = ROOT / "course" / folder(m)
        d.mkdir(parents=True, exist_ok=True)
        (d / "README.md").write_text(module_readme(m))
        intake = f"`/{m['intake']['skill']}`" if m["intake"]["skill"] else "planned"
        index.append(f"| {m['n']} | [{m['name']}]({folder(m)}/README.md) | {m['course']['status']} | {intake} |")
    if parked:
        index += ["", "**Parked for now** (outlines kept in `modules.json`): " + ", ".join(m["name"] for m in parked) + "."]
    (ROOT / "course" / "README.md").write_text("\n".join(index) + "\n")

    hub_map = {
        "about": "What exists in the AI Builders Hub: stages, modules, lessons and skills. Generated by tools/build_course.py from course/modules.json.",
        "updated": data["updated"],
        "community": COMMUNITY,
        "marketplace": {"name": MARKETPLACE["name"], "plugin": PLUGIN["name"], "plugin_version": PLUGIN["version"]},
        "stages": STAGES,
        "modules": [
            {
                "n": m["n"], "key": m["key"], "name": m["name"], "promise": m["promise"],
                "folder": f"course/{folder(m)}",
                "intake_skill": m["intake"]["skill"],
                "skills": [s["name"] for s in m["skills"]],
                "course": {
                    "title": m["course"]["title"], "status": m["course"]["status"],
                    "skool_course_id": m["course"]["skool_course_id"],
                    "lessons": [
                        {"part": p["part"], "title": l["title"], "skool_lesson_id": l["skool_lesson_id"]}
                        for p in m["course"]["parts"] for l in p["lessons"]
                    ],
                },
                "plugin_status": m["plugin_status"],
                "map_thread": m.get("map_thread"),
            }
            for m in mods
        ],
    }
    (ROOT / "hub-map.json").write_text(json.dumps(hub_map, ensure_ascii=False, indent=2) + "\n")
    print(f"{len(mods)} modules, course/README.md and hub-map.json written")


if __name__ == "__main__":
    main()
